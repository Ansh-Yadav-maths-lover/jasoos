const CATS = CATRAW.map(c => {
  const nm = c.n.split('|');
  const words = c.w.trim().split('\n').map(l => {
    const p = l.split('|');
    return { a: p[0].trim(), h: (p[1] || p[0]).trim() };
  }).filter(w => w.a);
  return { id: c.id, e: c.e, nm, words };
});
