function wtext(w, script) {
  if (!w) return '';
  const s = script || SET.script;
  if (s === 'hi') return w.h;
  if (s === 'en') return w.a;
  if (w.a === w.h) return w.a;
  return w.a + '<span class="alt">' + w.h + '</span>';
}
