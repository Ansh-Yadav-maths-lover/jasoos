/* ---------- engine ---------- */
const LS = k => { try { return localStorage.getItem(k); } catch (e) { return null; } };
const LSet = (k, v) => { try { localStorage.setItem(k, v); } catch (e) {} };
const DICT = {};
[STR, STR2, STR3].join('\n').split('\n').forEach(line => {
  if (!line || line.indexOf('|') < 0) return;
  const p = line.split('|');
  DICT[p[0].trim()] = [p[1], p[2], p[3]];
});
let LANG = LS('jas.lang') || '';
const LIDX = { hin: 0, hi: 1, en: 2 };
function setLang(id) {
  LANG = id; LSet('jas.lang', id);
  document.documentElement.lang = id === 'en' ? 'en' : 'hi';
  document.body.classList.toggle('l-hi', id === 'hi');
}
function t(key, vars) {
  const row = DICT[key];
  let s = row ? (row[LIDX[LANG] ?? 0] ?? row[0]) : key;
  if (vars) for (const k in vars) s = s.split('{' + k + '}').join(vars[k]);
  return s;
}
